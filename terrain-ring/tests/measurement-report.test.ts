/**
 * Writes ../MEASUREMENTS.md: numeric evidence for the blank and terrain fixtures.
 * Also asserts the key numbers so the report can't silently drift.
 */
import { writeFileSync } from "node:fs";
import { expect, it } from "vitest";
import { createRingMesh, facePreset, HEAD_SHAPES, meshVolume, openEdgeCount, type HeadShape, type Weight } from "../src/geometry/ring-blank";
import { createDemoSource, type TerrainSource } from "../src/geometry/heightmap";
import { buildTerrain, frameFor } from "../src/three/terrain-surface";

const RES = { faceSegments: 120, backSegments: 140, widthSegments: 60 };

function measure(weight: Weight, d: number, source: TerrainSource | null, height = 0.7, shape: HeadShape = "bar") {
  const preset = facePreset(weight, shape);
  const terrain = source ? buildTerrain(source, frameFor(5000, 0, preset), preset, { terrainHeight: height, detail: "high" }, 120) : null;
  const m = createRingMesh({ innerDiameterMm: d, weight: preset, shoulder: "classic", profile: "classic", terrain, resolution: RES });
  const P = m.positions;
  const yTop = d / 2 + preset.headHeightMm;
  let minR = Infinity, faceX = 0, faceZ = 0, maxY = -Infinity, bandZ = 0, minY = Infinity;
  for (let i = 0; i < P.length; i += 3) {
    const [x, y, z] = [P[i]!, P[i + 1]!, P[i + 2]!];
    minR = Math.min(minR, Math.hypot(x, y));
    maxY = Math.max(maxY, y);
    minY = Math.min(minY, y);
    // Footprint at the wall line: head points from just below the 0.15 mm edge round upward.
    if (i / 3 < (RES.faceSegments + 1) * (RES.widthSegments + 1)) { faceX = Math.max(faceX, Math.abs(x)); faceZ = Math.max(faceZ, Math.abs(z)); }
    if (y < -d / 2 && Math.abs(x) < 0.3) bandZ = Math.max(bandZ, Math.abs(z));
  }
  return {
    opening: minR * 2,
    faceL: faceX * 2,
    faceW: faceZ * 2,
    headAboveFinger: yTop - d / 2,
    terrainTop: maxY - yTop,
    bandWidth: bandZ * 2,
    bandThickness: -(d / 2) - minY,
    open: openEdgeCount(m),
    volume: meshVolume(m),
    relief: terrain?.reliefMm ?? 0
  };
}

const f = (n: number, dp = 2) => n.toFixed(dp);

it("writes the measurement report", () => {
  const lines: string[] = [
    "# Measurements: blank and terrain fixtures",
    "",
    "Generated by `tests/measurement-report.test.ts` from the geometry code (classic shoulders, comfort band).",
    "All values in millimetres. \"Open edges\" 0 = closed, consistently oriented shell at preview resolution.",
    "",
    "## Blank (flat face) across face sizes and finger sizes",
    "",
    "| Head | Face size | Target opening | Measured opening | Face L × W (target) | Face L × W (measured) | Head above finger | Band width | Band thickness | Volume mm³ | Open edges |",
    "|---|---|---|---|---|---|---|---|---|---|---|"
  ];
  for (const shape of ["bar", "cushion"] as HeadShape[]) for (const w of ["slim", "standard", "bold"] as Weight[]) {
    for (const d of [15, 17.2, 21.5]) {
      const r = measure(w, d, null, 0.7, shape);
      const p = facePreset(w, shape);
      expect(r.opening).toBeCloseTo(d, 3);
      expect(r.faceL).toBeCloseTo(p.faceLengthMm, 2);
      expect(r.faceW).toBeCloseTo(p.faceWidthMm, 2);
      expect(r.open).toBe(0);
      lines.push(`| ${HEAD_SHAPES[shape]} | ${p.label} | ${f(d, 1)} | ${f(r.opening, 3)} | ${p.faceLengthMm} × ${p.faceWidthMm} | ${f(r.faceL, 3)} × ${f(r.faceW, 3)} | ${f(r.headAboveFinger)} | ${f(r.bandWidth)} | ${f(r.bandThickness)} | ${f(r.volume, 0)} | ${r.open} |`);
    }
  }

  const fixtures: [string, TerrainSource][] = [
    ["Flat", { radiusM: 1e6, elevationAt: () => 200 }],
    ["Ramp (west→east)", { radiusM: 1e6, elevationAt: (e) => 300 + e * 0.15 }],
    ["Peak on the perimeter", { radiusM: 1e6, elevationAt: (e, n) => 200 + 900 * Math.exp(-(((e - 2500) / 400) ** 2 + (n / 400) ** 2)) }],
    ["Mountainous (synthetic)", createDemoSource()]
  ];
  lines.push("", "## Terrain fixtures (Standard face, 17.2 mm, 70% height)", "",
    "| Fixture | Relief applied | Highest terrain above table | Opening | Open edges |", "|---|---|---|---|---|");
  for (const [name, src] of fixtures) {
    const r = measure("standard", 17.2, src);
    expect(r.open).toBe(0);
    expect(r.opening).toBeCloseTo(17.2, 3);
    lines.push(`| ${name} | ${f(r.relief)} | ${f(r.terrainTop)} | ${f(r.opening, 3)} | ${r.open} |`);
  }
  lines.push("", "Not covered here: self-intersection, wall thickness, castable feature size (see MANUFACTURING_CHECKS.md).", "");
  writeFileSync("../MEASUREMENTS.md", lines.join("\n"));
});
